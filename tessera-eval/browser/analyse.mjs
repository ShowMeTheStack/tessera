// Analyse, SV view and console. node analyse.mjs <url> <outdir>
import { chromium } from 'playwright';
const [url, out] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(url);
await page.waitForTimeout(1500);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForTimeout(2500);
await page.locator('.tab[data-tab="analyse"]').click();
await page.locator('button', { hasText: 'Logic levels' }).click();
await page.waitForTimeout(800);
console.log('levels', await page.evaluate(() => [...document.querySelectorAll('.an-path')].map((e) => e.querySelector('.an-n').textContent + ' ' + e.querySelector('.an-end').textContent).join(' | ')));
await page.locator('.an-path').first().click();
await page.waitForTimeout(300);
console.log('lit', await page.evaluate(() => Studio.app.canvas.selectedNets().length + ' nets'));
await page.locator('button', { hasText: 'Estimate resources' }).click();
await page.waitForTimeout(12000);
console.log('resources', await page.evaluate(() => [...document.querySelectorAll('.an-cell')].map((e) => e.textContent).join(' ')));
await page.screenshot({ path: out + '/analyse.png' });
await page.locator('.tab[data-tab="code"]').click();
await page.locator('.seg-b[data-v="sv"]').click();
await page.waitForTimeout(800);
console.log('sv first lines', await page.evaluate(() => [...document.querySelectorAll('.code-pane pre:not([hidden]) .ln')].slice(0, 3).map((e) => e.textContent).join(' / ')));
await page.locator('.tab[data-tab="console"]').click();
await page.waitForTimeout(400);
console.log('console lines', await page.evaluate(() => document.querySelectorAll('.con-line').length), await page.evaluate(() => [...document.querySelectorAll('.con-line .con-m')].slice(-3).map((e) => e.textContent).join(' || ')));
await page.screenshot({ path: out + '/console.png' });
await page.locator('.tab[data-tab="waves"]').click();
await page.waitForTimeout(400);
console.log('waves rows', await page.evaluate(() => document.querySelectorAll('.wv-name').length));
console.log(errors.length ? errors.join('\n') : 'no console errors');
await browser.close();

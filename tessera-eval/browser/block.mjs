// Hierarchy: make a block from a selection, open it, values inside, back out. node block.mjs <url> <outdir>
import { chromium } from 'playwright';
const [url, out] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(url);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForTimeout(1500);
const ids = await page.evaluate(() => Studio.app.doc.d.parts.filter((p) => ['add', 'const'].includes(p.type)).map((p) => 'p:' + p.id));
await page.evaluate((ids) => Studio.app.canvas.selectOnly(ids), ids);
await page.locator('.cv').focus().catch(() => {});
await page.keyboard.press('b');
await page.waitForTimeout(300);
await page.locator('.modal input').fill('Inc');
await page.keyboard.press('Enter');
await page.waitForTimeout(2500);
const top = await page.evaluate(() => ({ parts: Studio.app.doc.d.parts.map((p) => p.type + ':' + (p.params.name || p.params.block || '')), problems: (Studio.app.gen.problems || []).map((p) => p.message), java: Studio.app.gen.java }));
console.log('top parts', top.parts.join(' '), '| problems', JSON.stringify(top.problems));
console.log(top.java.split('\n').filter((l) => !l.startsWith('// tessera-studio')).join('\n'));
await page.evaluate(() => Studio.app.sim({ cmd: 'poke', path: 'en', value: '1' }));
await page.evaluate(() => Studio.app.sim({ cmd: 'run' }));
await page.waitForTimeout(2000);
await page.screenshot({ path: out + '/block-top.png' });
await page.locator('.cv .part', { hasText: 'Inc' }).first().dblclick();
await page.waitForTimeout(2000);
const inside = await page.evaluate(() => ({ level: Studio.app.doc.level(), parts: Studio.app.doc.d.parts.map((p) => p.type), values: [...Studio.app.canvas.values.entries()].map(([k, v]) => k + '=' + v) }));
console.log('inside', JSON.stringify(inside));
await page.screenshot({ path: out + '/block-inside.png' });
await page.keyboard.press('Escape');
await page.keyboard.press('Escape');
await page.waitForTimeout(800);
console.log('after esc level', await page.evaluate(() => Studio.app.doc.level()));
await page.keyboard.press('Meta+z');
await page.waitForTimeout(1500);
console.log('after undo', await page.evaluate(() => Studio.app.doc.d.parts.map((p) => p.type).join(' ')));
console.log(errors.length ? errors.join('\n') : 'no console errors');
await browser.close();

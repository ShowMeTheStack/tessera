    @AfterAll
    static void stats() {
        STATS.entrySet().stream().sorted(Map.Entry.comparingByKey()).forEach(e -> System.out.printf(
                "GEN-STATS %s: riscv-tests %d cycles, %d retired, CPI %.3f%n", e.getKey(), e.getValue()[0], e.getValue()[1],
                (double) e.getValue()[0] / e.getValue()[1]));
    }

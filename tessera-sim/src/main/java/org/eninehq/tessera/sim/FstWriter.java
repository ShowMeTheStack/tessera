package org.eninehq.tessera.sim;

import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.ValueLayout;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import org.eninehq.tessera.ir.Signal;

/**
 * Writes FST waveforms through the reference library ({@link FstNative}). FST files are much
 * smaller than VCD and carry extra information: enum literal names for {@code HwEnum} and
 * union tags (shown by GTKWave and Surfer), port directions and the Java source line of
 * every signal.
 */
final class FstWriter implements WaveWriter {
    private record Var(int handle, int slot, int width) {}

    private final FstNative.Lib lib = FstNative.lib();
    private final Arena arena = Arena.ofShared();
    private final MemorySegment ctx;
    private final List<Var> vars = new ArrayList<>();
    private final int clockHandle;
    private final MemorySegment buf;
    private final MemorySegment one, zero;
    private long[] last;

    private static final class Scope {
        final Map<String, Scope> kids = new TreeMap<>();
        final List<Map.Entry<String, Signal>> sigs = new ArrayList<>();
    }

    FstWriter(Path file, Netlist net) throws java.io.IOException {
        var parent = file.toAbsolutePath().getParent();
        if (parent != null) Files.createDirectories(parent);
        try {
            ctx = (MemorySegment) lib.writerCreate().invokeExact(arena.allocateFrom(file.toString()), 1);
            if (ctx.equals(MemorySegment.NULL)) throw new java.io.IOException("cannot create " + file);
            lib.setTimescale().invokeExact(ctx, -9);
            lib.setComment().invokeExact(ctx, arena.allocateFrom("Generated by Tessera"));
            var root = new Scope();
            int maxW = 1;
            for (var e : net.signalsByPath().entrySet()) {
                Signal s = e.getValue();
                if (net.isClock(s)) continue;
                if (net.slotOf(s) < 0) continue;
                String[] parts = e.getKey().split("\\.");
                Scope cur = root;
                for (int k = 0; k < parts.length - 1; k++) cur = cur.kids.computeIfAbsent(parts[k], x -> new Scope());
                cur.sigs.add(Map.entry(parts[parts.length - 1], s));
                maxW = Math.max(maxW, s.width());
            }
            buf = arena.allocate(maxW + 1L);
            one = arena.allocateFrom("1");
            zero = arena.allocateFrom("0");
            lib.setScope().invokeExact(ctx, FstNative.ST_VCD_MODULE, arena.allocateFrom("top"), MemorySegment.NULL);
            clockHandle = (int) lib.createVar().invokeExact(ctx, FstNative.VT_VCD_WIRE, FstNative.VD_INPUT, 1,
                    arena.allocateFrom("clock"), 0);
            var enums = new HashMap<String, Integer>();
            writeScope(root, net, enums);
            lib.setUpscope().invokeExact(ctx);
        } catch (java.io.IOException | RuntimeException e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        }
    }

    private void writeScope(Scope sc, Netlist net, Map<String, Integer> enums) throws Throwable {
        for (var e : sc.sigs) {
            Signal s = e.getValue();
            var ti = s.typeInfo();
            int vt = FstNative.VT_VCD_WIRE;
            if (ti != null && !ti.enumLiterals().isEmpty() && s.width() <= 16) {
                Integer table = enums.get(ti.javaType() + "/" + s.width());
                if (table == null) {
                    table = enumTable(ti.javaType(), ti.enumLiterals(), s);
                    enums.put(ti.javaType() + "/" + s.width(), table);
                }
                lib.emitEnumTableRef().invokeExact(ctx, (int) table);
                vt = FstNative.VT_SV_ENUM;
            }
            if (s.loc() != null && s.loc().line() > 0)
                lib.setSourceStem().invokeExact(ctx, arena.allocateFrom(s.loc().file()), s.loc().line(), 0);
            int dir = s.kind() == Signal.Kind.INPUT ? FstNative.VD_INPUT : s.kind() == Signal.Kind.OUTPUT ? FstNative.VD_OUTPUT
                    : FstNative.VD_IMPLICIT;
            String name = s.width() == 1 ? e.getKey() : e.getKey() + " [" + (s.width() - 1) + ":0]";
            int h = (int) lib.createVar().invokeExact(ctx, vt, dir, s.width(), arena.allocateFrom(name), 0);
            vars.add(new Var(h, net.slotOf(s), s.width()));
        }
        for (var k : sc.kids.entrySet()) {
            lib.setScope().invokeExact(ctx, FstNative.ST_VCD_MODULE, arena.allocateFrom(k.getKey()), MemorySegment.NULL);
            writeScope(k.getValue(), net, enums);
            lib.setUpscope().invokeExact(ctx);
        }
    }

    /** An FST enum table: union tags use the low bits of the value as the tag only when the signal is the tag itself. */
    private int enumTable(String name, List<String> literals, Signal s) throws Throwable {
        int n = Math.min(literals.size(), 1 << s.width());
        var lits = arena.allocate(ValueLayout.ADDRESS, n);
        var vals = arena.allocate(ValueLayout.ADDRESS, n);
        for (int i = 0; i < n; i++) {
            lits.setAtIndex(ValueLayout.ADDRESS, i, arena.allocateFrom(literals.get(i)));
            String bits = Long.toBinaryString(i);
            bits = "0".repeat(Math.max(0, s.width() - bits.length())) + bits;
            vals.setAtIndex(ValueLayout.ADDRESS, i, arena.allocateFrom(bits));
        }
        return (int) lib.createEnumTable().invokeExact(ctx, arena.allocateFrom(name), n, s.width(), lits, vals);
    }

    @Override public void sample(long cycle, long[] values) {
        try {
            lib.emitTime().invokeExact(ctx, cycle * 10);
            lib.emitValue().invokeExact(ctx, clockHandle, one);
            for (var var : vars) {
                int nw = BitVec.words(var.width());
                if (last != null && Arrays.equals(last, var.slot(), var.slot() + nw, values, var.slot(), var.slot() + nw)) continue;
                for (int b = 0; b < var.width(); b++) {
                    long word = values[var.slot() + (b >>> 6)];
                    buf.set(ValueLayout.JAVA_BYTE, var.width() - 1 - b, (byte) ((word >>> (b & 63) & 1) != 0 ? '1' : '0'));
                }
                lib.emitValue().invokeExact(ctx, var.handle(), buf);
            }
            if (last == null || last.length != values.length) last = values.clone();
            else System.arraycopy(values, 0, last, 0, values.length);
            lib.emitTime().invokeExact(ctx, cycle * 10 + 5);
            lib.emitValue().invokeExact(ctx, clockHandle, zero);
        } catch (RuntimeException e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        }
    }

    @Override public void close() {
        try {
            lib.writerClose().invokeExact(ctx);
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        } finally {
            arena.close();
        }
    }
}
